#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = join(packageRoot, "src", "companionPiBrokerExecutable.ts");
const generatedModule = join(packageRoot, "src", "companionPiBrokerSource.ts");

export async function bundleCompanionPiBroker() {
  const result = await build({
    absWorkingDir: packageRoot,
    entryPoints: [entry],
    bundle: true,
    packages: "bundle",
    platform: "node",
    format: "esm",
    target: "node20",
    minify: true,
    treeShaking: true,
    legalComments: "none",
    charset: "utf8",
    sourcemap: false,
    write: false,
    logLevel: "silent",
  });
  if (result.outputFiles?.length !== 1) throw new Error("expected one Pi broker bundle");
  const source = result.outputFiles[0].text;
  assertBuiltinOnlyImports(source);
  return source;
}

export function generatedSourceModule(source) {
  const encoded = Buffer.from(source, "utf8").toString("base64");
  return `/**
 * Generated by scripts/generate-companion-pi-broker.mjs. Do not edit by hand.
 * Base64 keeps the staged ESM byte-exact without template interpolation.
 */
export const COMPANION_PI_BROKER_SOURCE = Buffer.from(
  "${encoded}",
  "base64",
).toString("utf8");
`;
}

export function assertBuiltinOnlyImports(source) {
  const specifiers = [
    ...[...source.matchAll(/\bfrom\s*["']([^"']+)["']/g)].map((match) => match[1]),
    ...[...source.matchAll(/\bimport\s*\(\s*["']([^"']+)["']/g)].map((match) => match[1]),
    ...[...source.matchAll(/\brequire\s*\(\s*["']([^"']+)["']/g)].map((match) => match[1]),
  ].filter(Boolean);
  const unsafe = specifiers.filter((specifier) => !specifier.startsWith("node:"));
  if (unsafe.length > 0) {
    throw new Error(`Pi broker bundle retained non-builtin imports: ${unsafe.join(", ")}`);
  }
}

async function main() {
  const expected = generatedSourceModule(await bundleCompanionPiBroker());
  if (process.argv.includes("--check")) {
    const current = await readFile(generatedModule, "utf8");
    if (current !== expected) {
      process.stderr.write("companionPiBrokerSource.ts is stale; run broker:generate\n");
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(generatedModule, expected, { encoding: "utf8", mode: 0o644 });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
