#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

import { assertBuiltinOnlyImports } from "./generate-companion-pi-broker.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = join(packageRoot, "src", "companionBoxAgentExecutable.ts");
const generatedModule = join(packageRoot, "src", "companionBoxAgentSource.ts");

export async function bundleCompanionBoxAgent() {
  const result = await build({
    absWorkingDir: packageRoot,
    entryPoints: [entry],
    bundle: true,
    packages: "bundle",
    platform: "node",
    format: "esm",
    target: "node20",
    minify: true,
    treeShaking: true,
    legalComments: "none",
    charset: "utf8",
    sourcemap: false,
    write: false,
    logLevel: "silent",
  });
  if (result.outputFiles?.length !== 1) throw new Error("expected one Box agent bundle");
  const source = result.outputFiles[0].text;
  assertBuiltinOnlyImports(source);
  return source;
}

export function generatedSourceModule(source) {
  const encoded = Buffer.from(source, "utf8").toString("base64");
  return `/**
 * Generated by scripts/generate-companion-box-agent.mjs. Do not edit by hand.
 * Base64 keeps the staged ESM byte-exact without template interpolation.
 */
export const COMPANION_BOX_AGENT_SOURCE = Buffer.from(
  "${encoded}",
  "base64",
).toString("utf8");
`;
}

async function main() {
  const expected = generatedSourceModule(await bundleCompanionBoxAgent());
  if (process.argv.includes("--check")) {
    const current = await readFile(generatedModule, "utf8");
    if (current !== expected) {
      process.stderr.write("companionBoxAgentSource.ts is stale; run agent:generate\n");
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(generatedModule, expected, { encoding: "utf8", mode: 0o644 });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
